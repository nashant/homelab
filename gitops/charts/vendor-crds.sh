#!/bin/bash
# vendor-crds.sh traefik <traefik chart version> | gateway-api <release tag>
# Writes a CRD-only chart under charts/ from pinned upstream files. Rerun with a new version to bump.
set -euo pipefail
HERE=$(dirname "$(readlink -f "$0")")
TMP=$(mktemp -d); trap 'rm -rf $TMP' EXIT

case "${1:-}:${2:-}" in
traefik:?*)
  helm pull traefik --repo https://traefik.github.io/charts --version "$2" --untar -d $TMP
  APP=$(yq .appVersion $TMP/traefik/Chart.yaml)
  NAME=traefik-crds OUT=$HERE/traefik-crds/$APP SRC="traefik chart $2 crds/ (traefik.io only)"
  URL=https://github.com/traefik/traefik-helm-chart/tree/v$2/traefik/crds
  rm -rf $OUT; mkdir -p $OUT/crds-files
  cp $TMP/traefik/crds/traefik.io_*.yaml $OUT/crds-files/
  ;;
gateway-api:?*)
  curl -sfL -o $TMP/install.yaml https://github.com/kubernetes-sigs/gateway-api/releases/download/$2/standard-install.yaml
  APP=$2 NAME=gateway-api-crds OUT=$HERE/gateway-api-crds/$2 SRC="gateway-api $2 standard-install.yaml"
  URL=https://github.com/kubernetes-sigs/gateway-api/releases/tag/$2
  rm -rf $OUT; mkdir -p $OUT/crds-files $OUT/extra-files
  for crd in $(yq -N 'select(.kind=="CustomResourceDefinition")|.metadata.name' $TMP/install.yaml); do
    yq -N "select(.kind==\"CustomResourceDefinition\" and .metadata.name==\"$crd\")" $TMP/install.yaml \
      > $OUT/crds-files/${crd#*.}_${crd%%.*}.yaml
  done
  yq 'select(.kind != null and .kind != "CustomResourceDefinition")' $TMP/install.yaml > $OUT/extra-files/extras.yaml
  [ -s $OUT/extra-files/extras.yaml ] || rm -r $OUT/extra-files
  ;;
*) echo "usage: $0 traefik <chart version> | gateway-api <release tag>" >&2; exit 2 ;;
esac

cat > $OUT/Chart.yaml <<EOF
apiVersion: v2
name: $NAME
description: CRDs from $SRC, generated by charts/vendor-crds.sh
version: ${APP#v}
appVersion: $APP
sources:
- $URL
annotations:
  licenses: Apache-2.0
EOF

{
  echo "# One switch per file in crds-files/ (key = the part after the last \"_\")."
  echo "crds:"
  for f in $OUT/crds-files/*.yaml; do k=$(basename $f .yaml); echo "  ${k##*_}: true"; done
  echo "# Versions upstream defines but does not serve, to serve anyway: {<key>: [<version>, ...]}"
  echo "serve: {}"
  if [ -d $OUT/extra-files ]; then echo "# Non-CRD objects upstream ships with the CRDs (extra-files/)"; echo "extras: true"; fi
} > $OUT/values.yaml

mkdir -p $OUT/templates
cat > $OUT/templates/crds.yaml <<'EOF'
{{- range $path, $_ := .Files.Glob "crds-files/*.yaml" }}
{{- $key := $path | base | trimSuffix ".yaml" | splitList "_" | last }}
{{- if not (hasKey $.Values.crds $key) }}
{{- fail (printf "no .Values.crds.%s entry for vendored file %s" $key $path) }}
{{- end }}
{{- if index $.Values.crds $key }}
{{- $crd := $.Files.Get $path | fromYaml }}
{{- if hasKey $crd "Error" }}
{{- fail (printf "%s: %s" $path $crd.Error) }}
{{- end }}
{{- $_ := set $crd.metadata "annotations" (merge (dict "helm.sh/resource-policy" "keep") ($crd.metadata.annotations | default dict)) }}
{{- $serve := index $.Values.serve $key | default list }}
{{- $defined := list }}
{{- range $crd.spec.versions }}
{{- $defined = append $defined .name }}
{{- if has .name $serve }}
{{- $_ := set . "served" true }}
{{- end }}
{{- end }}
{{- range $serve }}
{{- if not (has . $defined) }}
{{- fail (printf "serve.%s: version %s is not defined upstream" $key .) }}
{{- end }}
{{- end }}
---
{{ toYaml $crd }}
{{- end }}
{{- end }}
EOF
if [ -d $OUT/extra-files ]; then
cat > $OUT/templates/extras.yaml <<'EOF'
{{- if .Values.extras }}
{{- range $path, $_ := .Files.Glob "extra-files/*.yaml" }}
---
{{ $.Files.Get $path }}
{{- end }}
{{- end }}
EOF
fi

echo "wrote ${OUT#$HERE/}: $(ls $OUT/crds-files | wc -l) CRDs from $SRC"
[ -d $OUT/extra-files ] && echo "  extras: $(yq -N '.kind + "/" + .metadata.name' $OUT/extra-files/extras.yaml | tr '\n' ' ')"
helm template $NAME $OUT >/dev/null && echo "  helm template: ok"
